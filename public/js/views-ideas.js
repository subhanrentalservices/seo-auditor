// UI for own ideas: I2 page change log, I3 edit locally, I4 internal link ideas, I5 what AI would quote,
// I8 ask Claude for a fix, I10 robots tester.
import { h, mount, api, toast, shortUrl, table } from "./core.js";
import { VIEWS, NAV, pageSections } from "./views.js";

NAV.splice(NAV.findIndex((n) => n.view === "pages") + 1, 0, { view: "links", label: "Link ideas" });

// I5 + I3 + I8 in the page drawer
pageSections.unshift(async (ctx, d) => {
  const x = d.page.data || {}, aid = d.page.audit_id, url = d.page.url;
  const parts = [];
  if (x.bestPassage) {
    const b = x.bestPassage;
    const verdict = b.words >= 134 && b.words <= 167 && b.pos <= 40 ? ["up", "✓ Strong: right length, near the top"] : b.words < 100 ? ["", "! Short for a citation; aim for 134–167 words"] : b.pos > 40 ? ["", "! Found late on the page; move a direct answer higher"] : ["", "! Usable; 134–167 words near the top is ideal"];
    parts.push(h("div", { class: "card" }, h("h3", { style: { marginBottom: "6px" } }, "What AI would quote"),
      h("p", { class: "small muted", style: { marginTop: 0 } }, `${b.words} words · starts ${b.pos}% into the page · `, h("span", { class: verdict[0] }, verdict[1])),
      h("div", { class: "quote" }, b.text)));
  } else if (d.page.indexable) parts.push(h("div", { class: "card" }, h("h3", { style: { marginBottom: "6px" } }, "What AI would quote"), h("p", { class: "muted", style: { margin: 0 } }, "No paragraph of 40+ words found. AI answers need a self-contained passage to cite.")));

  const src = await api(`/api/audits/${aid}/source?url=${encodeURIComponent(url)}`).catch(() => null);
  if (src?.configured) parts.push(h("div", { class: "card" }, h("h3", { style: { marginBottom: "6px" } }, "Edit locally"),
    src.file ? [h("p", { class: "small", style: { marginTop: 0 } }, h("a", { href: src.vscode }, src.file), " (opens in VS Code)"),
      src.hits.length ? h("ul", { class: "small" }, src.hits.map((hh) => h("li", {}, hh.title, " — ", hh.line ? h("a", { href: hh.vscode }, `line ${hh.line}`) : h("span", { class: "muted" }, "no single line")))) : null]
      : h("p", { class: "small muted", style: { margin: 0 } }, "No matching file in the local folder (tried ", src.tried.join(", "), "). It may be generated by PHP or a CMS.")));

  if (d.issues.length) {
    const out = h("div", {});
    const btn = h("button", { class: "btn", onclick: async () => {
      btn.disabled = true; btn.textContent = "Asking Claude… (up to a minute)";
      try { const r = await api(`/api/audits/${aid}/ask-claude`, { method: "POST", body: { url } }); mount(out, h("div", { class: "quote", style: { whiteSpace: "pre-wrap", marginTop: "10px" } }, r.answer)); }
      catch (e) { toast(e.message); }
      btn.disabled = false; btn.textContent = "Ask again";
    } }, "Ask Claude for a fix");
    parts.push(h("div", { class: "card" }, h("div", { class: "card-h" }, h("h3", {}, "Fix suggestions"), btn),
      h("p", { class: "small muted", style: { margin: 0 } }, "Runs Claude Code on this PC with your subscription. It gets this page's details and issues, has no tools, and only writes suggestions; nothing on the site changes."), out));
  }
  return parts.length ? h("div", { class: "stack" }, parts) : null;
});

// I4
VIEWS.links = async (ctx) => {
  if (!ctx.auditData) return h("div", { class: "card empty" }, "Run an audit first.");
  const rows = await api(`/api/audits/${ctx.auditData.audit.id}/link-opportunities`);
  const base = ctx.project.start_url;
  const head = h("div", { class: "card" }, h("h2", {}, "Internal link ideas"),
    h("p", { class: "hint", style: { margin: 0 } }, "Pages with the fewest internal links, and other pages that already mention their topic but don't link to them. Turn the quoted words into a link: it helps Google and AI find and understand the weaker page."));
  if (!rows.length) return [head, h("div", { class: "card empty" }, "No suggestions — either every page is well linked, or this audit was made before link ideas existed (run a new audit).")];
  return [head, ...rows.map((t) => h("div", { class: "card" },
    h("div", { class: "card-h" }, h("h3", {}, shortUrl(t.target, base)), h("span", { class: "small muted" }, `${t.inlinks} internal link${t.inlinks === 1 ? "" : "s"} now`)),
    h("p", { class: "small muted", style: { marginTop: 0 } }, t.title),
    table([{ label: "Add a link on", cls: "url", get: (s) => shortUrl(s.from, base) }, { label: "Anchor text", get: (s) => h("b", {}, s.anchor) },
      { label: "Where", get: (s) => h("span", { class: "small muted" }, s.context) }], t.suggestions)))];
};

// I2: wrap the history screen
const historyView = VIEWS.history;
VIEWS.history = async (ctx) => {
  const base = await historyView(ctx);
  if (!ctx.auditData) return base;
  const c = await api(`/api/audits/${ctx.auditData.audit.id}/changes`);
  if (!c.previous) return base;
  const risky = c.changes.filter((x) => x.risky).length;
  const card = h("div", { class: "card" }, h("div", { class: "card-h" }, h("h2", {}, `Page changes since ${new Date(c.previous.finished_at + "Z").toLocaleString("en-AU")}`),
      risky ? h("span", { class: "badge error" }, `${risky} risky`) : h("span", { class: "badge fixed" }, "nothing risky")),
    h("p", { class: "hint" }, "Title, description, H1, canonical, indexability, status, schema and big word-count changes per page. Risky changes (a page became noindex, lost its title or changed canonical) are listed first."),
    c.changes.length ? table([{ label: "Page", cls: "url", get: (r) => shortUrl(r.url, ctx.project.start_url) },
      { label: "Changes", get: (r) => h("div", {}, r.changes.map((ch) => h("div", { class: "small" }, ch.risk ? h("span", { class: "down" }, "✕ ") : "• ", h("b", {}, ch.field), ": ",
        h("span", { class: "muted" }, String(ch.from).slice(0, 90) || "(empty)"), " → ", String(ch.to).slice(0, 90) || "(empty)"))) }], c.changes)
      : h("p", { class: "muted" }, "No page changed between these audits."));
  return [...[base].flat(), card];
};

// I10: wrap the AI audit screen with a robots tester
const aiView = VIEWS.ai;
VIEWS.ai = async (ctx) => {
  const base = await aiView(ctx);
  const input = h("input", { type: "text", value: "/", placeholder: "/path or full URL", style: { width: "320px" } });
  const out = h("div", {});
  const test = async (e) => {
    e?.preventDefault();
    try {
      const r = await api(`/api/projects/${ctx.project.id}/robots-test`, { method: "POST", body: { url: input.value } });
      mount(out, h("p", { class: "small muted" }, r.found ? `${r.robotsUrl}` : `No robots.txt at ${r.robotsUrl} — everything is allowed.`),
        table([{ label: "Crawler", key: "bot" }, { label: "Result", get: (x) => (x.allowed ? h("span", { class: "up" }, "✓ allowed") : h("span", { class: "down" }, "✕ blocked")) },
          { label: "Rule that decides", get: (x) => (x.rule ? h("code", {}, `line ${x.line}: ${x.rule}`) : h("span", { class: "muted" }, "no rule (allowed by default)")) }], r.rows));
    } catch (err) { toast(err.message); }
  };
  return [...[base].flat(), h("form", { class: "card", onsubmit: test }, h("h2", {}, "Robots.txt tester"),
    h("p", { class: "hint" }, "Check whether Google, Bing and each AI crawler may fetch a URL, and which robots.txt line decides it. Reads the live robots.txt."),
    h("div", { class: "row" }, input, h("button", { class: "btn" }, "Test")), out)];
};
